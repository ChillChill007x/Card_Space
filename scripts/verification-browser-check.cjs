// ทดสอบขั้นตอนยืนยันพ่อค้าผ่านเบราว์เซอร์: ส่งหลักฐาน ขอแก้ไข ส่งใหม่ อนุมัติ และลงขาย
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const { createStore } = await import('../server/store.js');
  const { createApp, hashPassword } = await import('../server/app.js');
  const store = await createStore();
  await store.addUser({ id:'admin', name:'Admin', email:'admin@test.local', passwordHash:hashPassword('test-password-123'), role:'admin', verification:'none' });
  const server = createApp(store).listen(0,'127.0.0.1');
  await new Promise(r => server.once('listening',r));
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const base = `http://127.0.0.1:${server.address().port}`;
    const seller = await browser.newPage({ viewport:{width:1440,height:1100} });
    const admin = await browser.newPage();
    const errors = []; [seller,admin].forEach(p => p.on('pageerror', e => errors.push(e.message)));
    await seller.goto(base);
    await seller.locator('.hero-tilt.front').hover({position:{x:90,y:45}});
    await seller.waitForFunction(() => getComputedStyle(document.querySelector('.hero-tilt.front .card-surface')).transform.startsWith('matrix3d'));
    await seller.locator('#search').fill('Ember');
    await seller.waitForFunction(() => document.querySelectorAll('.card').length === 1);
    await seller.locator('.card-art').hover({position:{x:60,y:40}});
    await seller.waitForFunction(() => getComputedStyle(document.querySelector('.card .card-surface')).transform.startsWith('matrix3d'));
    await seller.request.post(base+'/api/auth/register',{data:{name:'Seller',email:'seller@test.local',password:'test-password-123',role:'merchant'}});
    await seller.reload();
    await seller.locator('#header-sell').click();
    await seller.locator('#verification-form').waitFor();
    // กรอกฟอร์มยืนยันร้านพร้อมแนบรูปหลักฐาน แล้วกดส่ง (ใช้ซ้ำตอนส่งครั้งแรกและส่งใหม่)
    const submit = async () => {
      for (const [k,v] of Object.entries({fullName:'Test Seller',shopName:'Browser Shop',phone:'0812345678',address:'Test address'})) await seller.locator(`[name="${k}"]`).fill(v);
      await seller.locator('[name="proof"]').setInputFiles({name:'proof.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')});
      await seller.locator('#verification-form .dark').click();
      await seller.waitForFunction(() => !document.querySelector('#dialog').open && document.querySelector('#merchant-status').textContent.includes('ส่งหลักฐานแล้ว'));
    };
    await submit();
    await seller.locator('#my-shop').click();
    await seller.locator('#shop-verification details').waitFor();
    if(await seller.locator('dialog[open]').count())throw Error('Pending shop reopened form');
    if(!await seller.locator('#new-listing').isDisabled())throw Error('Pending shop can list');
    await seller.locator('#shop-verification summary').click();
    await seller.locator('#shop-verification .verification-proof').waitFor({state:'visible'});
    await admin.request.post(base+'/api/auth/login',{data:{email:'admin@test.local',password:'test-password-123'}});
    await admin.goto(base); await admin.locator('#admin-nav').click();
    await admin.locator('#admin-search').fill('sell-000001');
    await admin.locator('.admin-row').waitFor();
    if(await admin.locator('.admin-row').count()!==1)throw Error('Merchant code search failed');
    if(await admin.locator('dialog[open]').count()) throw Error('Admin navigation opened a modal');
    if(await seller.locator('#admin-nav').isVisible()) throw Error('Merchant sees admin navigation');
    await admin.locator('details summary').click();
    await admin.locator('.verification-proof').waitFor({state:'visible'});
    await admin.locator('[data-note]').fill('Please upload clearer proof');
    await admin.locator('[data-status="rejected"]').click();
    await admin.waitForFunction(() => document.querySelector('[data-filter="rejected"] strong')?.textContent === '1');
    await seller.locator('#shop-status-refresh').click();
    await seller.locator('#shop-verify-edit').click();
    await seller.waitForFunction(() => document.querySelector('#dialog-content').textContent.includes('Please upload clearer proof'));
    await submit();
    await admin.locator('#admin-reload').click();
    await admin.locator('[data-status="approved"]').click();
    await admin.waitForFunction(() => document.querySelector('[data-filter="approved"] strong')?.textContent === '1');
    await admin.locator('[data-filter="approved"]').click();
    await admin.screenshot({path:'tmp/admin-desktop.png',fullPage:true});
    await admin.setViewportSize({width:390,height:844});
    if(await admin.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Admin mobile overflow');
    await admin.screenshot({path:'tmp/admin-mobile.png',fullPage:true});
    await seller.reload(); await seller.locator('#header-sell').click();
    await seller.locator('#listing-form').waitFor();
    for(const name of ['backImage','detailImage'])await seller.locator(`details:has([name="${name}"]) summary`).click();
    for (const [k,v] of Object.entries({name:'Browser approved card',set:'TEST',rarity:'SR',price:'200',backImage:'/art/moon.svg',detailImage:'/art/forest.svg',conditionNotes:'Test notes'})) await seller.locator(`[name="${k}"]`).fill(v);
    await seller.locator('#listing-form input[type=file]').first().setInputFiles({name:'card.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64')});
    await seller.locator('.listing-preview').first().waitFor({state:'visible'});
    await seller.locator('#listing-form .dark').click();
    await seller.waitForFunction(() => [...document.querySelectorAll('.card h3')].some(el => el.textContent === 'Browser approved card'));
    if (!(await store.cards()).find(c=>c.name==='Browser approved card').image.startsWith('/api/uploads/')) throw Error('Upload not saved');
    await seller.locator('.card').filter({hasText:'Browser approved card'}).click();
    await seller.locator('[data-side="detail"]').click();
    if((await seller.locator('#product-image').getAttribute('src'))!=='/art/forest.svg') throw Error('Detail gallery failed');
    await seller.setViewportSize({width:390,height:844});
    await seller.locator('#account').click(); await seller.locator('#verification').click();
    await seller.locator('#verification-form').waitFor();
    if (await seller.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile overflow');
    await seller.screenshot({path:'tmp/verification-mobile.png'});
    if(errors.length) throw Error(errors.join('\n'));
    console.log('Passed: 3D hero/card, search, proof submission, admin rejection, correction, approval, listing, mobile and no JavaScript errors.');
  } finally { await browser.close(); await new Promise(r=>server.close(r)); }
})().catch(e=>{console.error(e);process.exit(1);});
