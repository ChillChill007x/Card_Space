// Optional browser check: install Playwright or point PLAYWRIGHT_MODULE to its module path.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:3000');
  await page.locator('.card').first().waitFor();
  if (await page.locator('.card').count() !== 8) throw Error('Expected 8 seed cards');
  fs.mkdirSync('tmp', { recursive: true });
  const hero = page.locator('.hero-tilt.front');
  await hero.hover({ position: { x: 90, y: 45 } });
  await page.waitForFunction(() => document.querySelector('.hero-tilt.front').classList.contains('is-tilting'));
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.hero-tilt.front .card-surface')).transform.startsWith('matrix3d'));
  await page.mouse.move(5, 5);
  await page.screenshot({ path: 'tmp/desktop.png', fullPage: true });
  const art = page.locator('.card-art').first();
  const bounds = await art.boundingBox();
  const titleBefore = await page.locator('.card h3').first().boundingBox();
  await page.mouse.move(bounds.x + bounds.width * .8, bounds.y + bounds.height * .25);
  await page.waitForFunction(() => document.querySelector('.card').classList.contains('is-tilting'));
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.card .card-surface')).transform.startsWith('matrix3d'));
  const titleAfter = await page.locator('.card h3').first().boundingBox();
  if (titleBefore.y !== titleAfter.y) throw Error('Text moved with artwork');
  await page.screenshot({ path: 'tmp/hover.png', fullPage: true });
  await page.mouse.move(5, 5);
  await page.waitForFunction(() => !document.querySelector('.card').classList.contains('is-tilting'));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await art.hover();
  if (await page.locator('.card .card-surface').first().evaluate(el => getComputedStyle(el).transform) !== 'none') throw Error('Reduced motion ignored');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.mouse.move(5, 5);
  // Touch-primary devices must still respond to actual mouse events.
  const hybrid = await browser.newContext({ hasTouch: true });
  const hybridPage = await hybrid.newPage();
  await hybridPage.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:3000');
  await hybridPage.locator('.card').first().waitFor();
  await hybridPage.locator('.card-art').first().hover();
  await hybridPage.waitForFunction(() => document.querySelector('.card').classList.contains('is-tilting'));
  await hybrid.close();
  await page.locator('#search').fill('Ember');
  await page.waitForFunction(() => document.querySelector('#count').textContent === 'พบ 1 รายการ');
  await page.locator('.card').click();
  await page.locator('#product-image').waitFor();
  await page.locator('.breadcrumbs a').first().click();
  await page.locator('#reset').click();
  await page.waitForFunction(() => document.querySelectorAll('.card').length === 8);
  await page.locator('[data-category="One Piece"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.card').length === 2);
  await page.locator('#reset').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelectorAll('.card').length === 8);
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile overflow');
  await page.screenshot({ path: 'tmp/mobile.png', fullPage: true });
  await page.locator('#account').click();
  await page.locator('#switch-auth').click();
  await page.locator('[name="name"]').fill('UI tester');
  await page.locator('[name="email"]').fill(`ui-${Date.now()}@test.local`);
  await page.locator('[name="password"]').fill('test-password-123');
  await page.locator('[name="role"]').selectOption('merchant');
  await page.locator('#auth-form button[type="submit"]').click();
  await page.waitForFunction(() => document.querySelector('#account').textContent.includes('UI tester'));
  await page.locator('#sell').click();
  await page.locator('#verification-form').waitFor();
  if (!(await page.locator('#dialog-content').textContent()).includes('ยืนยันบัญชีพ่อค้า')) throw Error('Pending merchant not explained');
  if (errors.length) throw Error(errors.join('\n'));
  console.log('Browser checks passed: 3D hover/reset, stable text, reduced motion, catalog, search, category, detail, mobile layout, registration, pending merchant; no JS errors.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
