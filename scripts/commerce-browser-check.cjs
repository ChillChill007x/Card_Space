const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');

// Dedicated ephemeral server keeps browser fixtures out of the user's demo.
(async () => {
  const { createStore } = await import('../server/store.js');
  const { createApp, hashPassword } = await import('../server/app.js');
  const store = await createStore();
  const password = 'browser-test-password';
  const seller = { id: 'browser-seller', name: 'Test Seller', email: 'seller@browser.local', passwordHash: hashPassword(password), role: 'merchant', verification: 'approved', balance: 0 };
  await store.addUser(seller);
  await store.addCard({ id: 'browser-card', name: 'Browser Test Card', category: 'Pokémon', set: 'TEST001', price: 10000, rarity: 'SR', condition: 'Near Mint', image: '/art/fire.svg', sellerId: seller.id, sellerName: seller.name, description: 'Demo description with full details.\nSecond line of description.', language: 'English', conditionNotes: 'Demo condition notes', shippingNotes: 'Demo protective sleeve and rigid packaging', backImage: '/art/moon.svg', createdAt: new Date().toISOString() });
  const server = createApp(store).listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const base = `http://127.0.0.1:${server.address().port}`;
    const buyerContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const sellerContext = await browser.newContext();
    const buyerPage = await buyerContext.newPage(), sellerPage = await sellerContext.newPage();
    const errors = [];
    for (const page of [buyerPage, sellerPage]) page.on('pageerror', e => errors.push(e.message));
    await buyerPage.goto(base);
    await buyerPage.locator('.card').first().waitFor();
    await buyerPage.locator('#account').click();
    await buyerPage.locator('#switch-auth').click();
    await buyerPage.locator('[name="name"]').fill('Demo Buyer');
    await buyerPage.locator('[name="email"]').fill('buyer@browser.local');
    await buyerPage.locator('[name="password"]').fill(password);
    await buyerPage.locator('#auth-form button[type="submit"]').click();
    await buyerPage.waitForFunction(() => document.querySelector('#account').textContent.includes('Demo Buyer'));
    await buyerPage.locator('#wallet').click();
    await buyerPage.locator('#topup-form button').click();
    await buyerPage.waitForFunction(() => document.querySelector('.balance-panel strong')?.textContent === '฿1,000');
    fs.mkdirSync('tmp', { recursive: true });
    await buyerPage.screenshot({ path: 'tmp/wallet-mobile.png' });
    await buyerPage.locator('#close-dialog').click();
    await buyerPage.locator('[data-id="browser-card"]').click();
    await buyerPage.locator('#product-image').waitFor();
    if (await buyerPage.locator('dialog[open]').count()) throw Error('Product still uses a modal');
    if (!buyerPage.url().includes('#/cards/browser-card')) throw Error('Missing product URL');
    await buyerPage.locator('[data-side="back"]').click();
    if (!(await buyerPage.locator('#product-image').getAttribute('src')).includes('moon.svg')) throw Error('Back image not selected');
    await buyerPage.reload();
    await buyerPage.locator('#product-image').waitFor();
    if (!(await buyerPage.locator('.detail-panel').first().textContent()).includes('Demo description')) throw Error('Description missing');
    await buyerPage.screenshot({ path: 'tmp/product-mobile.png', fullPage: true });
    await buyerPage.setViewportSize({ width: 1440, height: 1000 });
    const stage = buyerPage.locator('.product-stage');
    const box = await stage.boundingBox();
    await buyerPage.mouse.move(box.x + box.width * .8, box.y + box.height * .2);
    await buyerPage.waitForFunction(() => getComputedStyle(document.querySelector('.product-stage .card-surface')).transform.startsWith('matrix3d'));
    await buyerPage.screenshot({ path: 'tmp/product-desktop.png', fullPage: true });
    await buyerPage.mouse.move(1,1);
    await buyerPage.goBack();
    await buyerPage.locator('[data-id="browser-card"]').waitFor({ state: 'visible' });
    await buyerPage.goForward();
    await buyerPage.locator('#product-image').waitFor();
    await buyerPage.setViewportSize({ width: 390, height: 844 });

    await buyerPage.locator('#buy-card').click();
    await buyerPage.locator('[name="recipient"]').fill('Demo Buyer');
    await buyerPage.locator('[name="phone"]').fill('0000000000');
    await buyerPage.locator('[name="address"]').fill('Demo Buyer 0000000000 Sample Road 10000');
    await buyerPage.screenshot({ path: 'tmp/checkout-mobile.png', fullPage: true });
    if (await buyerPage.locator('dialog[open]').count()) throw Error('Checkout still uses modal');
    await buyerPage.locator('#checkout-form button').click();
    await buyerPage.locator('.order-status.paid').waitFor();
    if (await buyerPage.locator('dialog[open]').count()) throw Error('Orders still use a modal');
    await buyerPage.screenshot({ path: 'tmp/orders-mobile.png', fullPage: true });
    // Separate merchant session: navigate through the visible store controls.
    await sellerPage.goto(base);
    await sellerPage.locator('.card').first().waitFor();
    await sellerPage.locator('#account').click();
    await sellerPage.locator('[name="email"]').fill(seller.email);
    await sellerPage.locator('[name="password"]').fill(password);
    await sellerPage.locator('#auth-form button[type="submit"]').click();
    await sellerPage.waitForFunction(() => document.querySelector('#account').textContent.includes('Test Seller'));
    await sellerPage.locator('#my-shop').click();
    await sellerPage.locator('#shop-orders').click();
    await sellerPage.locator('[data-action="ship"]').click();
    await sellerPage.locator('[name="tracking"]').fill('Demo Express DEMO001');
    await sellerPage.locator('[name=receipt]').setInputFiles({name:'shipment.png',mimeType:'image/png',buffer:await sellerPage.screenshot()});
    await sellerPage.locator('.receipt-preview').waitFor({state:'visible'});
    await sellerPage.locator('#order-action-form .dark').click();
    await sellerPage.locator('.order-status.shipped').waitFor();
    await buyerPage.locator('#orders-nav').click();
    await buyerPage.locator('.shipment-evidence summary').click();
    await buyerPage.waitForFunction(()=>document.querySelector('.shipment-evidence img')?.naturalWidth>0);
    await buyerPage.locator('[data-action="receive"]').click();
    await buyerPage.locator('[name=receipt]').setInputFiles({name:'receipt.png',mimeType:'image/png',buffer:await buyerPage.screenshot()});
    await buyerPage.locator('.receipt-preview').waitFor({state:'visible'});
    await buyerPage.locator('#order-action-form .dark').click();
    await buyerPage.locator('.order-status.completed').waitFor();
    await buyerPage.locator('.receipt-evidence:not(.shipment-evidence) summary').click();
    await buyerPage.waitForFunction(()=>document.querySelector('.receipt-evidence:not(.shipment-evidence) img')?.naturalWidth>0);
    if (seller.balance !== 10000) throw Error('Merchant was not credited after delivery');
    // A cancelled sample order restores credit and listing availability.
    await buyerPage.locator('[data-status-filter="completed"]').click();
    await buyerPage.locator('#order-search').fill('no-such-card');
    await buyerPage.locator('#clear-order-filters').click();
    await buyerPage.locator('.order-status.completed').waitFor();
    await buyerPage.setViewportSize({ width: 1440, height: 1000 });
    await buyerPage.screenshot({ path: 'tmp/orders-desktop.png', fullPage: true });
    await buyerPage.reload();
    await buyerPage.locator('.order-status.completed').waitFor();
    await buyerPage.setViewportSize({ width: 390, height: 844 });
    await buyerPage.locator('#market').click();
    await buyerPage.locator('[data-id="sample-5"]').click();
    await buyerPage.locator('#buy-card').click();
    await buyerPage.locator('[name="recipient"]').fill('Demo Buyer');
    await buyerPage.locator('[name="phone"]').fill('0000000000');
    await buyerPage.locator('[name="address"]').fill('Demo Buyer 0000000000 Sample Road 10000');
    await buyerPage.screenshot({ path: 'tmp/checkout-mobile.png', fullPage: true });
    if (await buyerPage.locator('dialog[open]').count()) throw Error('Checkout still uses modal');
    await buyerPage.locator('#checkout-form button').click();
    await buyerPage.locator('[data-action="cancel"]').click();
    await buyerPage.locator('#order-action-form .dark').click();
    await buyerPage.locator('.order-status.cancelled').waitFor();
    const buyer = (await store.users()).find(u => u.email === 'buyer@browser.local');
    if (buyer.balance !== 90000) throw Error('Incorrect final buyer balance');
    await buyerPage.locator('#wallet').click();
    await buyerPage.locator('#topup-form input').fill('10000000');
    await buyerPage.locator('#topup-form button').click();
    await buyerPage.waitForFunction(()=>document.querySelector('.balance-panel strong')?.textContent==='฿10,000,900');
    await buyerPage.locator('#close-dialog').click();
    if (await buyerPage.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile overflow');
    if (errors.length) throw Error(errors.join('\n'));
    console.log('Commerce browser checks passed: register, topup, purchase, merchant shipping, receipt, seller credit, cancellation/refund, mobile layout, no JS errors.');
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exit(1); });
